def funcs(text):
 return {m[1]:{'params':re.findall(r'var (\w+)',m[2]),'body':m[3]} for m in re.finditer(r'^void (\w+)\(([^\n]*)\)\n\{\n(.*?)^\}',text,re.M|re.S)}
def branch(body,diff):
 active=True;out=[]
 for raw in body.splitlines():
  s=raw.strip()
  if s.startswith('!'): active=s=='!*' or diff in s[1:];continue
  if active or s.endswith(':') or s.startswith('+'): out.append(s)
 return '\n'.join(out)
def choose(body,diff):
 # ECL argument order is Easy, Normal, Hard, Lunatic after the output register.
 i={'E':0,'N':1,'H':2,'L':3}[diff]
